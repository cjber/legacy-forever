"""Generate one continuous terrain alpha mask per exploration area."""

import argparse
import math
import subprocess
from collections import defaultdict
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
WIDTH, HEIGHT, FEATHER = 1002, 668, 40


def read_rings(text):
    groups = defaultdict(list)
    for line in text.splitlines():
        fields = line.split("\t")
        zone, key = int(fields[0]), fields[1]
        groups[(zone, key)].append(
            [(float(fields[i]) * WIDTH, float(fields[i + 1]) * HEIGHT) for i in range(3, len(fields), 2)]
        )
    return groups


def alpha_mask(rings):
    """Union the terrain rings, then fade outward by exact distance to their segments.

    Explore rings represent separate filled terrain islands, as MapContents.Triangles does, not holes.
    Alpha is evaluated once per pixel, so nearby edges never compound within an area.
    """
    points = [point for ring in rings for point in ring]
    left = math.floor(min(p[0] for p in points)) - FEATHER
    top = math.floor(min(p[1] for p in points)) - FEATHER
    right = math.ceil(max(p[0] for p in points)) + FEATHER
    bottom = math.ceil(max(p[1] for p in points)) + FEATHER
    width = 1 << (right - left - 1).bit_length()
    height = 1 << (bottom - top - 1).bit_length()
    inside = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(inside)
    for ring in rings:
        draw.polygon([(x - left, y - top) for x, y in ring], fill=255)
    yy, xx = np.indices((height, width), dtype=np.float32)
    xx += left + 0.5
    yy += top + 0.5
    distance = np.full((height, width), np.inf, dtype=np.float32)
    for ring in rings:
        for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1], strict=False):
            dx, dy = x2 - x1, y2 - y1
            length = dx * dx + dy * dy
            if length == 0:
                continue
            t = np.clip(((xx - x1) * dx + (yy - y1) * dy) / length, 0, 1)
            np.minimum(distance, np.hypot(xx - x1 - t * dx, yy - y1 - t * dy), out=distance)
    alpha = np.where(np.asarray(inside) > 0, 255, np.clip((1 - distance / FEATHER) * 255, 0, 255)).astype(np.uint8)
    rgba = np.zeros((height, width, 4), dtype=np.uint8)
    rgba[:, :, 3] = alpha
    return Image.fromarray(rgba), left, top


def generate(groups, output, manifest):
    output.mkdir(parents=True, exist_ok=True)
    lines = ["-- Generated by tools/generate_masks_all.py, do not edit.", "local _, ns = ...", "ns.ShadingMasks = {"]
    previous_zone = None
    expected = set()
    for index, ((zone, key), rings) in enumerate(sorted(groups.items())):
        image, left, top = alpha_mask(rings)
        basename = f"Mask{index:03d}"
        path = output / f"{basename}.tga"
        expected.add(path)
        image.save(path, compression="tga_rle")
        if zone != previous_zone:
            if previous_zone is not None:
                lines.append("\t},")
            lines.append(f"\t[{zone}] = {{")
            previous_zone = zone
        texture = r"Interface\\AddOns\\LegacyForever\\media\\legacy-masks\\" + basename
        lines.append(f'\t\t["{key}"] = {{ {left}, {top}, {image.width}, {image.height}, "{texture}" }},')
    if previous_zone is not None:
        lines.append("\t},")
    lines.append("}")
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text("\n".join(lines) + "\n")
    # Only this generator's numbered assets can be stale; unrelated media is never removed.
    for path in output.iterdir():
        if path.is_file() and path.suffix == ".tga" and path.stem.startswith("Mask") and path.stem[4:].isdigit():
            if path not in expected:
                path.unlink()
    return expected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rings", type=Path)
    parser.add_argument("--output", type=Path, default=ROOT / "media/legacy-masks")
    parser.add_argument("--manifest", type=Path, default=ROOT / "Data/ShadingMasks.lua")
    args = parser.parse_args()
    text = (
        args.rings.read_text()
        if args.rings
        else subprocess.check_output(
            ["luajit", str(ROOT / "tools/export_shading_rings.lua"), str(ROOT / "Data/Explore.lua")], text=True
        )
    )
    groups = read_rings(text)
    paths = generate(groups, args.output, args.manifest)
    print(
        f"Generated {len(paths)} masks across {len({zone for zone, _ in groups})} maps: "
        f"{sum(p.stat().st_size for p in paths)} bytes"
    )


if __name__ == "__main__":
    main()
